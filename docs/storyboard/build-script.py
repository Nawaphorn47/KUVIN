from docx import Document
from docx.shared import Pt, Cm, RGBColor
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.oxml.ns import qn

d = Document()
sec = d.sections[0]
sec.left_margin = sec.right_margin = Cm(2.2)
sec.top_margin = sec.bottom_margin = Cm(2)
st = d.styles["Normal"]
st.font.name = "Leelawadee UI"
st.font.size = Pt(12)
st.element.rPr.rFonts.set(qn("w:eastAsia"), "Leelawadee UI")
GREEN = RGBColor(0x17, 0x6B, 0x5E)


def para(text="", bold=False, size=None, color=None, align=None, italic=False, after=4):
    p = d.add_paragraph()
    r = p.add_run(text)
    r.bold, r.italic = bold, italic
    if size: r.font.size = Pt(size)
    if color: r.font.color.rgb = color
    if align: p.alignment = align
    p.paragraph_format.space_after = Pt(after)
    return p


def scene(no, title, place):
    para(f"ฉากที่ {no}  {title}", bold=True, size=14, color=GREEN, after=0)
    para(place, italic=True, size=10.5, after=4)


def act(text):
    para(f"({text})", italic=True, size=11, after=3)


def line(who, text):
    p = d.add_paragraph()
    p.paragraph_format.left_indent = Cm(0.5)
    p.paragraph_format.space_after = Pt(3)
    r = p.add_run(f"{who}: ")
    r.bold = True
    p.add_run(text)


