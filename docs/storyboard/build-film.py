def shot(s):
    n, loc, size, cam, bg, art, act, snd, sec = s
    if bg == "ins":
        inner = f'<img src="{art[0][0]}">'
    elif bg == "title":
        inner = 'KUVIN<small>เรียกวิน เรียกความสบายใจ · kuvinn.tech</small>'
    else:
        inner = "".join(f'<span class="e" style="left:{x}%;top:{y}%;font-size:{z}px">{e}</span>' for e, x, y, z in art)
    return (f'<div class="shot"><div class="fr {bg}"><span class="tag">ช็อต {n}</span><span class="sz">{esc(size)} · {sec} วิ</span>{inner}</div>'
            f'<div class="info"><b>{esc(loc)}</b> · กล้อง: {esc(cam)}<br>{esc(act)}<div class="d">{esc(snd)}</div></div></div>')


def act_pages():
    flat = [(a[0], a[1], a[2], sh) for a in ACTS for sh in a[3]]
    out = ""
    for i in range(0, len(flat), 6):
        chunk = flat[i:i + 6]
        acts = []
        for a in chunk:
            label = f"{a[0]}: {a[1]}"
            if label not in acts:
                acts.append(label)
        a0, a1 = chunk[0][3][0], chunk[-1][3][0]
        out += (f'<section class="page"><header><span class="no">ช็อต {a0}–{a1}</span><h2>{esc(" · ".join(acts))}</h2>'
                f'<span class="time">{esc(chunk[0][2].split("–")[0])}</span></header><div class="grid">{"".join(shot(c[3]) for c in chunk)}</div></section>')
    return out


